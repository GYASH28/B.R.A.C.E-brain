#!/usr/bin/env node
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
const root=path.resolve(import.meta.dirname,'..');
const read=r=>fs.readFileSync(path.join(root,r),'utf8');
const home=read('index.html');
const guide=read('guide/index.html');
const css=read('scrollcraft-v3.css');
const js=read('scrollcraft-v3.js');
const manifest=JSON.parse(read('manifest.webmanifest'));
assert.equal((home.match(/<h1[ >]/g)||[]).length,1,'homepage must have exactly one h1');
assert.equal((guide.match(/<h1[ >]/g)||[]).length,1,'guide must have exactly one h1');
assert.match(home,/scrollcraft-v3\.css/,'homepage must load the new Scrollcraft v3 visual system');
assert.match(home,/scrollcraft-v3\.js/,'homepage must load the new Scrollcraft v3 runtime');
assert.doesNotMatch(home,/cinematic-(?:base|scenes|polish)\.css/,'legacy homepage visual layers must stay retired');
assert.match(home,/data-opening-film/,'opening film must exist');
assert.match(home,/brace-opening\.mp4/,'desktop opening film must exist');
assert.match(home,/brace-opening-portrait\.mp4/,'mobile opening film must exist');
assert.match(home,/class="hero-topography"/,'new procedural hero visual must exist');
assert.match(home,/data-live-chat/,'living memory console must exist');
const hero=home.split('<section id="hero"')[1]?.split('</section>')[0]||'';
assert.doesNotMatch(hero,/app-(?:graph|overview|inbox|recall|connections|settings)\.(?:png|jpg|webp)/i,'hero must not recycle old application screenshots');
assert.match(home,/data-side-scroll/,'horizontal narrative must exist');
assert.match(home,/data-flow-rail/,'horizontal narrative rail must exist');
assert.match(home,/data-brain-peak/,'graph cinematic section must exist');
assert.match(css,/prefers-reduced-motion:reduce/,'homepage must flatten motion for reduced-motion users');
assert.match(css,/backdrop-filter/,'frosted glass language must remain present');
assert.match(js,/requestAnimationFrame\(renderScroll\)/,'scroll choreography must be frame-synchronised');
assert.match(js,/lerp\(visualScroll, target/,'visual scroll-linked transforms must be smoothed without hijacking native scroll');
assert.match(js,/data\.braceRuntime|braceRuntime/,'runtime readiness marker must exist');
assert.match(js,/playScenario/,'continuous interactive chat runtime must exist');
assert.match(js,/updateOpening/,'opening film must be scroll-driven');
assert.equal(manifest.short_name,'BRACE');
assert.equal(manifest.start_url,'/');
assert.match(read('robots.txt'),/Sitemap:/,'robots file needs sitemap');
assert.match(read('sitemap.xml'),/\/guide\//,'sitemap must include beginner guide');
console.log('SCROLLCRAFT_V3_CONTRACT_OK');
